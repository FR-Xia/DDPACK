function figureHandle = plot(solution, varargin)
%PLOT Plot states, controls, convergence, and a 2-D/3-D trajectory.
parser = inputParser;
addParameter(parser, 'Visible', true, @(x) islogical(x) && isscalar(x));
parse(parser, varargin{:});
if ~isstruct(solution) || ~all(isfield(solution, {'states', 'controls', 'time'}))
    error('ddpack:plot:InvalidSolution', 'A normalized DDPACK solution is required.');
end
visibility = 'off';
if parser.Results.Visible
    visibility = 'on';
end
figureHandle = figure('Visible', visibility, 'Color', 'w', ...
    'Name', sprintf('DDPACK %s solution', upper(solution.algorithm)), ...
    'Position', [100, 100, 1200, 760]);

subplot(2, 2, 1);
workspaceDimension = solution.metadata.workspace_dimension;
if workspaceDimension == 3 && size(solution.states, 1) >= 3
    plot3(solution.states(1, :), solution.states(2, :), solution.states(3, :), ...
        'Color', [0.00, 0.35, 0.70], 'LineWidth', 2, ...
        'DisplayName', 'Trajectory');
    hold on;
    plot3(solution.states(1, 1), solution.states(2, 1), solution.states(3, 1), ...
        'o', 'Color', [0.00, 0.45, 0.70], 'MarkerFaceColor', [0.00, 0.45, 0.70], ...
        'DisplayName', 'Start');
    target = solution.metadata.problem.xf;
    plot3(target(1), target(2), target(3), ...
        's', 'Color', [0.85, 0.33, 0.10], 'MarkerFaceColor', [0.85, 0.33, 0.10], ...
        'DisplayName', 'Goal');
    plot3(solution.states(1, end), solution.states(2, end), solution.states(3, end), ...
        'x', 'Color', [0.45, 0.10, 0.65], 'LineWidth', 1.6, ...
        'MarkerSize', 8, 'DisplayName', 'Final');
    centers = solution.metadata.problem.obstacle_centers;
    radii = solution.metadata.problem.obstacle_radii;
    safetyMargin = solution.metadata.problem.safety_margin;
    [sphereX, sphereY, sphereZ] = sphere(28);
    for obstacle = 1:size(centers, 2)
        visibility = obstacleVisibility(obstacle);
        surf(centers(1, obstacle) + radii(obstacle)*sphereX, ...
            centers(2, obstacle) + radii(obstacle)*sphereY, ...
            centers(3, obstacle) + radii(obstacle)*sphereZ, ...
            'FaceColor', [0.85, 0.25, 0.10], 'FaceAlpha', 0.28, ...
            'EdgeColor', 'none', 'HandleVisibility', visibility, ...
            'DisplayName', 'Obstacle');
        if safetyMargin > 0
            safetyRadius = radii(obstacle) + safetyMargin;
            mesh(centers(1, obstacle) + safetyRadius*sphereX, ...
                centers(2, obstacle) + safetyRadius*sphereY, ...
                centers(3, obstacle) + safetyRadius*sphereZ, ...
                'FaceColor', 'none', 'EdgeColor', [0.75, 0.15, 0.10], ...
                'EdgeAlpha', 0.30, 'HandleVisibility', visibility, ...
                'DisplayName', 'Safety');
        end
    end
    zlabel('z (m)'); view(-25, 24); axis equal;
elseif workspaceDimension == 2 && size(solution.states, 1) >= 2
    plot(solution.states(1, :), solution.states(2, :), ...
        'Color', [0.00, 0.35, 0.70], 'LineWidth', 2, ...
        'DisplayName', 'Trajectory');
    hold on;
    plot(solution.states(1, 1), solution.states(2, 1), 'o', ...
        'Color', [0.00, 0.45, 0.70], 'MarkerFaceColor', [0.00, 0.45, 0.70], ...
        'DisplayName', 'Start');
    target = solution.metadata.problem.xf;
    plot(target(1), target(2), 's', ...
        'Color', [0.85, 0.33, 0.10], 'MarkerFaceColor', [0.85, 0.33, 0.10], ...
        'DisplayName', 'Goal');
    plot(solution.states(1, end), solution.states(2, end), 'x', ...
        'Color', [0.45, 0.10, 0.65], 'LineWidth', 1.6, ...
        'MarkerSize', 8, 'DisplayName', 'Final');
    centers = solution.metadata.problem.obstacle_centers;
    radii = solution.metadata.problem.obstacle_radii;
    safetyMargin = solution.metadata.problem.safety_margin;
    for obstacle = 1:size(centers, 2)
        angle = linspace(0, 2*pi, 100);
        visibility = obstacleVisibility(obstacle);
        fill(centers(1, obstacle) + radii(obstacle) * cos(angle), ...
            centers(2, obstacle) + radii(obstacle) * sin(angle), ...
            [0.90, 0.45, 0.10], 'FaceAlpha', 0.25, ...
            'EdgeColor', [0.65, 0.20, 0.05], ...
            'HandleVisibility', visibility, 'DisplayName', 'Obstacle');
        if safetyMargin > 0
            safetyRadius = radii(obstacle) + safetyMargin;
            plot(centers(1, obstacle) + safetyRadius*cos(angle), ...
                centers(2, obstacle) + safetyRadius*sin(angle), '--', ...
                'Color', [0.75, 0.15, 0.10], 'LineWidth', 1.2, ...
                'HandleVisibility', visibility, 'DisplayName', 'Safety');
        end
    end
    axis equal;
else
    plot(solution.time, solution.states(1, :), ...
        'Color', [0.00, 0.35, 0.70], 'LineWidth', 2);
end
xlabel('x (m)'); ylabel('y (m)'); title('Trajectory'); grid on;
if workspaceDimension >= 2
    legend('Location', 'northoutside', 'Orientation', 'horizontal', ...
        'NumColumns', 4, 'FontSize', 7.5, 'Box', 'off');
end

subplot(2, 2, 2);
plot(solution.time, solution.states.', 'LineWidth', 1.5);
xlabel('Time (s)'); ylabel('State'); title('States'); grid on;

subplot(2, 2, 3);
stairs(solution.time, solution.controls.', 'LineWidth', 1.5);
xlabel('Time (s)'); ylabel('Control'); title('Controls'); grid on;

subplot(2, 2, 4);
if isfinite(solution.metadata.metrics.analytic_zoh_clearance_lower_bound)
    axis off;
    audit = solution.metadata.metrics;
    text(0.05,0.85,'Independent analytic ZOH verification','FontWeight','bold');
    text(0.05,0.65,sprintf('Clearance lower bound: %.6g m', ...
        audit.analytic_zoh_clearance_lower_bound));
    text(0.05,0.45,sprintf('Replay terminal error: %.6g', ...
        audit.analytic_zoh_terminal_error));
    text(0.05,0.25,'64 subintervals per held control; speed-based bound');
    text(0.05,0.10,'Applies to this kinematic model; no disturbance guarantee');
elseif isempty(solution.cost_history)
    axis off;
    text(0.5, 0.5, 'No cost history returned', 'HorizontalAlignment', 'center');
else
    if numel(solution.trial_cost_history) > 1
        semilogy(max(solution.trial_cost_history, eps), ...
            'Color', [0.72, 0.72, 0.72], 'LineWidth', 0.9, ...
            'DisplayName', 'Trial');
        hold on;
    end
    semilogy(max(solution.cost_history, eps), ...
        'Color', [0.80, 0.30, 0.05], 'LineWidth', 1.8, ...
        'DisplayName', 'Best accepted');
    xlabel('Iteration'); ylabel('Cost'); title('Accepted-cost convergence'); grid on;
    legend('Location', 'best', 'FontSize', 8, 'Box', 'off');
end
sgtitle(sprintf('%s: %s', upper(solution.algorithm), solution.status), ...
    'Interpreter', 'none');
end

function value = obstacleVisibility(obstacleIndex)
if obstacleIndex == 1, value = 'on'; else, value = 'off'; end
end
