function solution = normalizeSolution(raw, algorithm, problem, runtimeSeconds)
%NORMALIZESOLUTION Convert solver-native output to the public schema.

problem = applyLegacyValidationAliases(problem);
problem = applyValidationDefaults(problem);
[identity, wasLegacy] = ddpack.resolveAlgorithm(algorithm, 'Warn', false);
canonicalAlgorithm = identity.algorithm_id;
legacyAlgorithm = '';
if wasLegacy, legacyAlgorithm = lower(char(algorithm)); end

if ~isstruct(raw) || ~isfield(raw, 'x') || ~isfield(raw, 'u')
    error('ddpack:solution:InvalidRawOutput', ...
        'Solver output must contain x and u fields.');
end
states = toNumericTrajectory(raw.x, 'states');
nativeControlCount = trajectoryLength(raw.u);
controls = toNumericTrajectory(raw.u, 'controls');
[time, timeMetadata] = reconstructPhysicalTime( ...
    raw, canonicalAlgorithm, problem, size(states, 2));
if size(controls, 2) >= size(states, 2)
    controls = controls(:, 1:size(states, 2));
elseif size(controls, 2) == size(states, 2) - 1
    controls(:, end + 1) = controls(:, end);
else
    error('ddpack:solution:ControlLength', ...
        'Control trajectory must have N or N-1 samples for N states.');
end

trialCostHistory = extractHistory(raw, 'J');
acceptedCostHistory = extractHistory(raw, 'J_accepted');
if isempty(acceptedCostHistory)
    acceptedCostHistory = trialCostHistory;
end
[metrics, defectDiagnostics] = ddpack.computeMetrics( ...
    states, controls, time, problem, acceptedCostHistory, canonicalAlgorithm, raw);
solverError = isfield(raw, 'error') && any(raw.error(:) ~= 0);
[solverConvergencePass, solverConvergenceReported] = convergencePass(raw);
independentDefectPass = true;
if isfinite(problem.independent_dynamics_defect_tolerance)
    independentDefectPass = ...
        metrics.high_accuracy_absolute_dynamics_defect <= ...
        problem.independent_dynamics_defect_tolerance;
end
numericalChecksPass = metrics.finite_values_pass && ...
    metrics.dynamics_diagnostics_complete && ...
    metrics.dimension_check_pass && metrics.time_monotonic_pass && metrics.time_bounds_pass && ...
    metrics.initial_error <= problem.initial_tolerance && ...
    metrics.terminal_error <= problem.terminal_tolerance && ...
    applicableLessEqual(metrics.maximum_state_constraint_violation, ...
        problem.constraint_tolerance) && ...
    metrics.maximum_control_constraint_violation <= problem.constraint_tolerance && ...
    metrics.absolute_dynamics_defect <= problem.dynamics_defect_tolerance && ...
    independentDefectPass && ...
    applicableGreaterEqual(metrics.analytic_zoh_clearance_lower_bound, 0) && ...
    applicableLessEqual(metrics.analytic_zoh_terminal_error, problem.terminal_tolerance) && ...
    (~problem.require_cost_decrease || metrics.cost_decreased) && ...
    applicableGreaterEqual(metrics.minimum_obstacle_clearance, ...
        -problem.constraint_tolerance);
success = numericalChecksPass && solverConvergencePass && ~solverError;

if solverError && isfield(raw,'numerical_diagnostics')
    status = 'numerical_failure';
    message = sprintf('Numerical failure: %s. %s', ...
        raw.numerical_diagnostics.failure_identifier,raw.numerical_diagnostics.failure_message);
elseif success
    status = 'converged';
    message = 'Solver convergence and independent numerical checks passed.';
elseif numericalChecksPass && solverConvergenceReported
    status = 'feasible_not_converged';
    message = sprintf('Numerical checks passed, but solver status is %s.', ...
        metrics.convergence_status);
else
    status = 'failed_checks';
    message = sprintf(['Numerical checks failed: terminal=%.6g, control=%.6g, ' ...
        'state=%.6g, clearance=%.6g, Euler defect=%.6g, RK4 defect=%.6g, ' ...
        'analytic clearance bound=%.6g, analytic terminal=%.6g, cost decreased=%d, time-bound violation=%.6g s.'], metrics.terminal_error, ...
        metrics.maximum_control_constraint_violation, ...
        metrics.maximum_state_constraint_violation, ...
        metrics.minimum_obstacle_clearance, ...
        metrics.absolute_dynamics_defect, ...
        metrics.high_accuracy_absolute_dynamics_defect, ...
        metrics.analytic_zoh_clearance_lower_bound, metrics.analytic_zoh_terminal_error, metrics.cost_decreased,metrics.time_bound_violation);
    if ~metrics.dynamics_diagnostics_complete
        message=sprintf('%s Dynamics diagnostics incomplete at step %g: %s: %s', ...
            message,defectDiagnostics.failure_step,defectDiagnostics.failure_identifier,defectDiagnostics.failure_message);
    end
end

iterations = numel(acceptedCostHistory);
if isfield(raw, 'iter') && isnumeric(raw.iter) && isscalar(raw.iter)
    iterations = raw.iter;
end
objective = metrics.returned_objective;
metrics.success = success;
metrics.status = status;
metrics.objective = objective;
metrics.iteration_count = iterations;
metrics.runtime_seconds = runtimeSeconds;
metrics.numerical_checks_pass = numericalChecksPass;
metrics.solver_convergence_pass = solverConvergencePass;
if isfield(raw,'numerical_diagnostics')
    metrics.numerical_diagnostics = raw.numerical_diagnostics;
end

applicability = struct( ...
    'maximum_state_constraint_violation', applicabilityLabel( ...
        metrics.maximum_state_constraint_violation), ...
    'maximum_control_constraint_violation', 'applicable', ...
    'minimum_obstacle_clearance', applicabilityLabel( ...
        metrics.minimum_obstacle_clearance), ...
    'minimum_segment_obstacle_clearance', applicabilityLabel( ...
        metrics.minimum_segment_obstacle_clearance), ...
    'minimum_pairwise_distance', 'not_applicable', ...
    'high_accuracy_dynamics_defect_tolerance', ...
        toleranceApplicability(problem.independent_dynamics_defect_tolerance));

solution = struct( ...
    'success', success, ...
    'status', status, ...
    'message', message, ...
    'algorithm', canonicalAlgorithm, ...
    'algorithm_id', canonicalAlgorithm, ...
    'algorithm_name', identity.public_name, ...
    'implementation_status', identity.implementation_status, ...
    'legacy_algorithm_name', legacyAlgorithm, ...
    'reference_relation', identity.reference_relation, ...
    'states', states, ...
    'controls', controls, ...
    'time', time, ...
    'objective', objective, ...
    'cost_history', acceptedCostHistory, ...
    'trial_cost_history', trialCostHistory, ...
    'accepted_cost_history', acceptedCostHistory, ...
    'iterations', iterations, ...
    'runtime_seconds', runtimeSeconds, ...
    'terminal_error', metrics.terminal_error, ...
    'absolute_dynamics_defect', metrics.absolute_dynamics_defect, ...
    'relative_dynamics_defect', metrics.relative_dynamics_defect, ...
    'max_constraint_violation', metrics.max_constraint_violation, ...
    'maximum_state_constraint_violation', metrics.maximum_state_constraint_violation, ...
    'maximum_control_constraint_violation', metrics.maximum_control_constraint_violation, ...
    'min_obstacle_clearance', metrics.minimum_obstacle_clearance, ...
    'minimum_segment_obstacle_clearance', ...
        metrics.minimum_segment_obstacle_clearance, ...
    'minimum_pairwise_distance', metrics.minimum_pairwise_distance, ...
    'dynamics_defect', metrics.absolute_dynamics_defect, ...
    'finite_values_pass', metrics.finite_values_pass, ...
    'dimension_check_pass', metrics.dimension_check_pass, ...
    'accepted_objective', metrics.returned_objective, ...
    'termination_reason', metrics.termination_reason, ...
    'convergence_status', metrics.convergence_status, ...
    'metadata', struct('schema_version', 1, 'ddpack_version', ddpack.version(), ...
        'problem_name', problem.name, 'algorithm_identity', identity, ...
        'workspace_dimension', inferWorkspaceDimension(problem), ...
        'problem', publicProblemMetadata(problem), 'metrics', metrics, ...
        'metric_applicability', applicability, ...
        'time_grid', timeMetadata, ...
        'native_state_count', size(states, 2), ...
        'native_control_count', nativeControlCount, ...
        'defect_diagnostics', defectDiagnostics), ...
    'raw', raw);
end

function problem = applyValidationDefaults(problem)
% Keep direct result-normalization calls compatible with pre-1.0 problems.
defaults = struct( ...
    'name', 'unnamed_problem', ...
    'constraints', {{}}, ...
    'obstacle_centers', [], ...
    'obstacle_radii', [], ...
    'safety_margin', 0, ...
    'geometric_enforcement_margin', 0, ...
    'safety_gain', 0.5, ...
    'terminal_tolerance', 0.1, ...
    'constraint_tolerance', 1e-6, ...
    'initial_tolerance', 1e-10, ...
    'dynamics_defect_tolerance', 1e-6, ...
    'independent_dynamics_defect_tolerance', Inf, ...
    'require_cost_decrease', true, ...
    'minimum_time', [], ...
    'maximum_time', [], ...
    'terminal_projection_tolerance', [], ...
    'terminal_projection_max_iterations', 20);
names = fieldnames(defaults);
for index = 1:numel(names)
    if ~isfield(problem, names{index})
        problem.(names{index}) = defaults.(names{index});
    end
end
end

function problem = applyLegacyValidationAliases(problem)
aliases = {'gamma_h', 'safety_gain'; ...
    'cbf_enforcement_margin', 'geometric_enforcement_margin'};
for index = 1:size(aliases, 1)
    legacy = aliases{index, 1}; current = aliases{index, 2};
    if isfield(problem, legacy) && ~isfield(problem, current)
        warning('ddpack:DeprecatedProblemField', ...
            'problem.%s is deprecated; use problem.%s.', legacy, current);
        problem.(current) = problem.(legacy);
    end
end
end

function [time, metadata] = reconstructPhysicalTime(raw, algorithm, problem, count)
nativeTime = [];
if isfield(raw, 't') && isnumeric(raw.t) && numel(raw.t) == count
    nativeTime = raw.t(:).';
end
if isempty(nativeTime) || any(~isfinite(nativeTime)) || ...
        nativeTime(1) ~= 0 || any(diff(nativeTime) <= 0)
    nativeTime = linspace(0, problem.tf, count);
end

normalizedAlgorithms = {'terminal_defect_pddp', ...
    'geometric_safety_pddp_2d', 'geometric_safety_pddp_3d'};
isNormalized = any(strcmpi(algorithm, normalizedAlgorithms)) && ...
    abs(nativeTime(end) - 1) <= 1e-10;
optimizedHorizon = nativeTime(end);
source = 'solver_physical_time';
if isNormalized
    optimizedHorizon = lastValidHistoryValue(raw, 'final_time', NaN);
    if ~isfinite(optimizedHorizon)
        optimizedHorizon = lastValidHistoryValue(raw, 'Theta', problem.tf);
    end
    time = nativeTime * optimizedHorizon;
    source = 'solver_normalized_time_scaled_by_final_Theta';
else
    time = nativeTime;
end
metadata = struct('native_time', nativeTime, ...
    'native_time_is_normalized', isNormalized, ...
    'physical_time_source', source, ...
    'input_horizon', problem.tf, ...
    'optimized_horizon', optimizedHorizon, ...
    'control_hold', 'zero_order_hold', ...
    'solver_rollout_method', 'explicit_euler');
end

function value = lastValidHistoryValue(raw, fieldName, fallback)
value = fallback;
if ~isfield(raw, fieldName) || ~isnumeric(raw.(fieldName)), return; end
history = raw.(fieldName);
history = history(isfinite(history) & history > 0);
if ~isempty(history), value = history(end); end
end

function history = extractHistory(raw, fieldName)
history = [];
if isfield(raw, fieldName) && isnumeric(raw.(fieldName))
    history = raw.(fieldName);
    history = history(:);
    history = history(isfinite(history) & history ~= 0);
end
end

function pass = applicableLessEqual(value, tolerance)
pass = isnan(value) || value <= tolerance;
end

function pass = applicableGreaterEqual(value, tolerance)
pass = isnan(value) || value >= tolerance;
end

function label = applicabilityLabel(value)
if isnan(value), label = 'not_applicable'; else, label = 'applicable'; end
end

function label = toleranceApplicability(value)
if isfinite(value), label = 'applicable'; else, label = 'reported_not_gated'; end
end

function dimension = inferWorkspaceDimension(problem)
if ~isempty(problem.obstacle_centers)
    dimension = size(problem.obstacle_centers, 1);
elseif numel(problem.x0) == 3
    dimension = 2;
else
    dimension = min(3, numel(problem.x0));
end
end

function metadata = publicProblemMetadata(problem)
metadata = struct('x0', problem.x0, 'xf', problem.xf, ...
    'tf', problem.tf, 'dt', problem.dt, 'u_max', problem.u_max, ...
    'obstacle_centers', problem.obstacle_centers, ...
    'obstacle_radii', problem.obstacle_radii, ...
    'safety_margin', problem.safety_margin, ...
    'geometric_enforcement_margin', problem.geometric_enforcement_margin, ...
    'safety_gain', problem.safety_gain, ...
    'terminal_tolerance', problem.terminal_tolerance, ...
    'minimum_time', problem.minimum_time, ...
    'maximum_time', problem.maximum_time, ...
    'terminal_projection_tolerance', problem.terminal_projection_tolerance, ...
    'terminal_projection_max_iterations', problem.terminal_projection_max_iterations, ...
    'constraint_tolerance', problem.constraint_tolerance, ...
    'initial_tolerance', problem.initial_tolerance, ...
    'independent_dynamics_defect_tolerance', ...
        problem.independent_dynamics_defect_tolerance);
metadata.dynamics_defect_tolerance = problem.dynamics_defect_tolerance;
metadata.require_cost_decrease = problem.require_cost_decrease;
end

function [pass, reported] = convergencePass(raw)
reported = isfield(raw, 'convergence_status') && ...
    (ischar(raw.convergence_status) || isstring(raw.convergence_status));
if ~reported
    pass = true;
    return;
end
value = lower(strtrim(char(raw.convergence_status)));
pass = startsWith(value, 'converged');
end

function count = trajectoryLength(value)
if iscell(value), count = numel(value); else, count = size(value, 2); end
end

function matrix = toNumericTrajectory(value, fieldName)
if iscell(value)
    if isempty(value)
        error('ddpack:solution:EmptyTrajectory', '%s trajectory is empty.', fieldName);
    end
    widths = cellfun(@numel, value);
    if any(widths ~= widths(1))
        error('ddpack:solution:InconsistentCells', ...
            '%s cell entries have inconsistent dimensions.', fieldName);
    end
    matrix = zeros(widths(1), numel(value));
    for index = 1:numel(value), matrix(:, index) = value{index}(:); end
elseif isnumeric(value) && ismatrix(value) && ~isempty(value)
    matrix = value;
    if size(matrix, 1) > size(matrix, 2) && size(matrix, 2) <= 6
        matrix = matrix.';
    end
else
    error('ddpack:solution:InvalidTrajectory', ...
        '%s trajectory must be a numeric matrix or cell vector.', fieldName);
end
if any(~isfinite(matrix(:)))
    error('ddpack:solution:NonFiniteTrajectory', ...
        '%s trajectory contains NaN or Inf.', fieldName);
end
end
