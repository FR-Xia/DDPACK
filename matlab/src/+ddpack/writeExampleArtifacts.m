function writeExampleArtifacts(outputDir, solution, config, solverLog, figureHandle)
%WRITEEXAMPLEARTIFACTS Write one reproducible example artifact bundle.
if ~isfolder(outputDir)
    mkdir(outputDir);
end

writeText(fullfile(outputDir, 'config.json'), prettyJson(config));
metrics = solution.metadata.metrics;
metricsJson = metrics;
metricsJson.applicability = solution.metadata.metric_applicability;
writeText(fullfile(outputDir, 'metrics.json'), prettyJson(metricsJson));
writetable(struct2table(metrics, 'AsArray', true), ...
    fullfile(outputDir, 'metrics.csv'));
writeDefectArtifacts(outputDir, solution.metadata.defect_diagnostics);
if isfield(solution.raw,'line_search')
    writetable(array2table(solution.raw.line_search.trials, ...
        'VariableNames',solution.raw.line_search.trial_columns), ...
        fullfile(outputDir,'line_search_trials.csv'));
end
ddpack.save(solution, fullfile(outputDir, 'solution.mat'));
writeText(fullfile(outputDir, 'run.log'), solverLog);
writeText(fullfile(outputDir, 'summary.txt'), ...
    exampleSummary(solution, config));

environment = sprintf(['DDPACK version: %s\nMATLAB version: %s\n' ...
    'Computer: %s\nArchitecture: %s\nTimestamp: %s\n'], ...
    ddpack.version(), version, computer, computer('arch'), ...
    char(datetime('now', 'TimeZone', 'local')));
writeText(fullfile(outputDir, 'environment.txt'), environment);

if nargin >= 5 && ~isempty(figureHandle) && isgraphics(figureHandle)
    exportgraphics(figureHandle, fullfile(outputDir, 'trajectory.png'), ...
        'Resolution', 220);
    exportgraphics(figureHandle, fullfile(outputDir, 'trajectory.pdf'), ...
        'ContentType', 'vector');
end

fprintf(['[DDPACK] %s | terminal=%.6g | objective=%.6g | ' ...
    'constraint=%.6g | clearance=%.6g | runtime=%.6g s\n'], ...
    solution.algorithm, solution.terminal_error, solution.objective, ...
    solution.max_constraint_violation, solution.min_obstacle_clearance, ...
    solution.runtime_seconds);

function writeDefectArtifacts(outputDir, diagnostics)
writeText(fullfile(outputDir, 'defect_diagnostics.json'), prettyJson(diagnostics));
stepCount = numel(diagnostics.solver_consistent_step_norms);
if stepCount == 0, return; end
tableData = table((1:stepCount).', diagnostics.physical_time(2:end).', ...
    diagnostics.solver_consistent_step_norms(:), ...
    diagnostics.solver_consistent_relative_step_norms(:), ...
    diagnostics.high_accuracy_step_norms(:), ...
    diagnostics.high_accuracy_relative_step_norms(:), ...
    'VariableNames', {'step', 'time_end', 'solver_absolute_defect', ...
    'solver_relative_defect', 'rk4_absolute_defect', 'rk4_relative_defect'});
writetable(tableData, fullfile(outputDir, 'defect_diagnostics.csv'));

defectFigure = figure('Visible', 'off', 'Color', 'w', ...
    'Name', 'DDPACK defect diagnostics', 'Position', [100, 100, 900, 560]);
cleanup = onCleanup(@() close(defectFigure));
semilogy(1:stepCount, max(diagnostics.solver_consistent_step_norms, eps), ...
    'LineWidth', 1.6, 'DisplayName', 'Solver-consistent Euler');
hold on;
semilogy(1:stepCount, max(diagnostics.high_accuracy_step_norms, eps), ...
    'LineWidth', 1.6, 'DisplayName', 'Independent RK4');
xlabel('Segment'); ylabel('Absolute defect');
title('Dynamics Defect by Segment'); grid on; legend('Location', 'best');
exportgraphics(defectFigure, fullfile(outputDir, 'defect_diagnostics.png'), ...
    'Resolution', 220);
exportgraphics(defectFigure, fullfile(outputDir, 'defect_diagnostics.pdf'), ...
    'ContentType', 'vector');
end
end

function value = exampleSummary(solution, config)
stateDefinition = fieldOr(config, 'state_definition', 'see example source');
controlDefinition = fieldOr(config, 'control_definition', 'see example source');
lines = {'DDPACK example result', '', ...
    ['- Algorithm ID: `' solution.algorithm_id '`'], ...
    ['- Public name: ' solution.algorithm_name], ...
    ['- Implementation status: `' solution.implementation_status '`'], ...
    ['- State: ' stateDefinition], ...
    ['- Control: ' controlDefinition], ...
    ['- Initial condition: `' displayValue(fieldOr(config, ...
        'initial_condition', solution.metadata.problem.x0)) '`'], ...
    ['- Terminal target: `' displayValue(fieldOr(config, ...
        'terminal_target', solution.metadata.problem.xf)) '`'], ...
    ['- Constraints: ' fieldOr(config, 'constraints', ...
        'see config.json and problem metadata')], ...
    sprintf('- Final objective: %.12g', solution.objective), ...
    sprintf('- Terminal error: %.12g', solution.terminal_error), ...
    sprintf('- Maximum constraint violation: %.12g', solution.max_constraint_violation), ...
    sprintf('- Runtime (s): %.12g', solution.runtime_seconds), ...
    ['- Convergence status: `' solution.status '`']};
value = strjoin(lines, newline);
end

function value = displayValue(value)
if isnumeric(value) || islogical(value)
    value = mat2str(value);
elseif isstring(value)
    value = char(strjoin(value, ', '));
elseif ~ischar(value)
    value = jsonencode(value);
end
end

function value = fieldOr(data, name, fallback)
if isfield(data, name), value = data.(name); else, value = fallback; end
end

function value = prettyJson(data)
try
    value = jsonencode(data, 'PrettyPrint', true);
catch
    value = jsonencode(data);
end
end

function writeText(filename, value)
[fileId, message] = fopen(filename, 'w');
if fileId < 0
    error('ddpack:artifacts:OpenFailed', ...
        'Cannot open %s: %s', filename, message);
end
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, '%s', value);
end
