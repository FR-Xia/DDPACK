function result = example_energy_storage_management(varargin)
%EXAMPLE_ENERGY_STORAGE_MANAGEMENT Optimize a bounded storage-level process.
settings = ddpack.exampleSettings(mfilename, varargin{:});
rng(732, 'twister');
lowerBound = 0.25;

problem = struct('name', 'energy_storage_management', ...
    'x0', 0.65, 'xf', 0.353, 'tf', 15, 'dt', 0.3, 'interval', 50, ...
    'dynamics', PointMassDynamics(-0.03, 0.08, -0.005), ...
    'cost', QuadraticCost_fft(160, 3, 0.30), 'u_max', 0.8, ...
    'constraints', StateLowerBoundConstraint(1, lowerBound, 1), ...
    'terminal_tolerance', 5e-5, 'constraint_tolerance', 1e-8, ...
    'independent_dynamics_defect_tolerance', 0.02);
options = ddpack.Options('Algorithm', 'penalty_free_time_ddp', ...
    'MaxIterations', 100, 'Alpha', 0.20, 'QuickMode', settings.QuickMode);
solverLog = evalc('solution = ddpack.solve(problem, options);');
assert(solution.success, solution.message);
assert(solution.terminal_error <= problem.terminal_tolerance);
assert(min(solution.states(:)) >= lowerBound - problem.constraint_tolerance);

figureHandle = storageFigure(solution, lowerBound, problem.xf, settings.Visible);
config = struct('example', mfilename, 'algorithm_id', options.Algorithm, ...
    'random_seed', 732, 'quick_mode', settings.QuickMode, ...
    'state_definition', 'normalized stored-energy level', ...
    'control_definition', 'signed charge/discharge command', ...
    'initial_condition', problem.x0, 'terminal_target', problem.xf, ...
    'scenario', 'scheduled passive discharge to a 0.353 reserve level', ...
    'constraints', 'stored-energy level >= 0.25 and |command| <= 0.8', ...
    'units', struct('time', 's', 'state', 'normalized', 'control', 'normalized'));
ddpack.writeExampleArtifacts(settings.OutputDir, solution, config, solverLog, figureHandle);
result = struct('name', mfilename, 'solution', solution, ...
    'output_dir', settings.OutputDir, ...
    'state_definition', config.state_definition, ...
    'control_definition', config.control_definition);
if ~settings.Visible, close(figureHandle); end
end

function handle = storageFigure(solution, lowerBound, target, visible)
handle = figure('Visible', visible, 'Color', 'w', ...
    'Name', 'DDPACK energy storage management', 'Position', [100, 100, 1000, 700]);
layout = tiledlayout(handle, 2, 2, 'Padding', 'compact', 'TileSpacing', 'compact');
title(layout, 'Constrained Energy Storage Management');
nexttile; plot(solution.time, solution.states(1, :), 'LineWidth', 1.8); hold on;
yline(target, '--', 'Target'); yline(lowerBound, ':', 'Lower bound');
xlabel('Time (s)'); ylabel('Stored-energy level'); grid on;
nexttile; stairs(solution.time, solution.controls(1, :), 'LineWidth', 1.6);
yline(0.8, ':'); yline(-0.8, ':'); xlabel('Time (s)'); ylabel('Charge/discharge command'); grid on;
nexttile; semilogy(max(solution.trial_cost_history, eps), 'Color', [0.65, 0.65, 0.65]); hold on;
semilogy(max(solution.accepted_cost_history, eps), 'LineWidth', 1.8);
xlabel('Iteration'); ylabel('Cost'); legend('Trial', 'Accepted', 'Location', 'best'); grid on;
nexttile; plot(solution.time, solution.states(1, :) - lowerBound, 'LineWidth', 1.8); hold on;
yline(0, '--'); xlabel('Time (s)'); ylabel('Lower-bound margin'); grid on;
end
