function result = example_thermal_regulation(varargin)
%EXAMPLE_THERMAL_REGULATION Regulate a nonlinear non-spatial thermal process.
settings = ddpack.exampleSettings(mfilename, varargin{:});
rng(731, 'twister');

problem = struct('name', 'nonlinear_thermal_regulation', ...
    'x0', 2.0, 'xf', 0.032535, 'tf', 15, 'dt', 0.3, 'interval', 50, ...
    'dynamics', NonlinearThermalDynamics(), ...
    'cost', QuadraticCost_fft(120, 2.5, 0.25), 'u_max', 1.5, ...
    'constraints', {{}}, 'terminal_tolerance', 5e-5, ...
    'constraint_tolerance', 1e-10, ...
    'independent_dynamics_defect_tolerance', 0.05);
options = ddpack.Options('Algorithm', 'penalty_free_time_ddp', ...
    'MaxIterations', 220, 'Alpha', 0.20, 'QuickMode', settings.QuickMode);
solverLog = evalc('solution = ddpack.solve(problem, options);');
if settings.QuickMode
    assert(solution.finite_values_pass && solution.dimension_check_pass, ...
        solution.message);
else
    assert(solution.success, solution.message);
end

assert(solution.terminal_error <= problem.terminal_tolerance);
figureHandle = thermalFigure(solution, problem.xf, settings.Visible);
config = struct('example', mfilename, 'algorithm_id', options.Algorithm, ...
    'random_seed', 731, 'quick_mode', settings.QuickMode, ...
    'state_definition', 'normalized temperature deviation', ...
    'control_definition', 'signed heater/cooler command', ...
    'initial_condition', problem.x0, 'terminal_target', problem.xf, ...
    'scenario', 'scheduled passive nonlinear cool-down over 15 seconds', ...
    'constraints', '|heater/cooler command| <= 1.5', ...
    'units', struct('time', 's', 'state', 'normalized', 'control', 'normalized'));
ddpack.writeExampleArtifacts(settings.OutputDir, solution, config, solverLog, figureHandle);
result = struct('name', mfilename, 'solution', solution, ...
    'output_dir', settings.OutputDir, ...
    'state_definition', config.state_definition, ...
    'control_definition', config.control_definition);
if ~settings.Visible, close(figureHandle); end
end

function handle = thermalFigure(solution, target, visible)
handle = figure('Visible', visible, 'Color', 'w', ...
    'Name', 'DDPACK nonlinear thermal regulation', 'Position', [100, 100, 1000, 700]);
layout = tiledlayout(handle, 2, 2, 'Padding', 'compact', 'TileSpacing', 'compact');
title(layout, 'Nonlinear Thermal Regulation');
nexttile; plot(solution.time, solution.states(1, :), 'LineWidth', 1.8); hold on;
yline(target, '--', 'Target'); xlabel('Time (s)'); ylabel('Temperature deviation'); grid on;
nexttile; stairs(solution.time, solution.controls(1, :), 'LineWidth', 1.6);
yline(1.5, ':'); yline(-1.5, ':'); xlabel('Time (s)'); ylabel('Thermal command'); grid on;
nexttile; semilogy(max(solution.trial_cost_history, eps), 'Color', [0.65, 0.65, 0.65]); hold on;
semilogy(max(solution.accepted_cost_history, eps), 'LineWidth', 1.8);
xlabel('Iteration'); ylabel('Cost'); legend('Trial', 'Accepted', 'Location', 'best'); grid on;
nexttile; plot(solution.time, abs(solution.states(1, :) - target), 'LineWidth', 1.8);
xlabel('Time (s)'); ylabel('Absolute regulation error'); grid on;
end
