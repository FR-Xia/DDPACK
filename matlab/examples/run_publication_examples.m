function summary = run_publication_examples(varargin)
%RUN_PUBLICATION_EXAMPLES Run all stable, publication-facing examples.
parser = inputParser;
addParameter(parser, 'OutputDir', '', @(x) ischar(x) || isstring(x));
addParameter(parser, 'Visible', false, @(x) islogical(x) && isscalar(x));
addParameter(parser, 'QuickMode', false, @(x) islogical(x) && isscalar(x));
parse(parser, varargin{:}); settings = parser.Results;

exampleRoot = fileparts(mfilename('fullpath'));
repoRoot = fileparts(fileparts(exampleRoot));
addpath(fullfile(repoRoot, 'matlab', 'tools'));
setup_ddpack('IncludeExamples', true);
if strlength(string(settings.OutputDir)) == 0
    stamp = char(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));
    settings.OutputDir = fullfile(repoRoot, 'artifacts', 'example_runs', ['run_' stamp]);
end
settings.OutputDir = char(settings.OutputDir);
if isfolder(settings.OutputDir)
    error('ddpack:examples:ExistingOutput', ...
        'Refusing to overwrite an existing example run: %s', settings.OutputDir);
end
mkdir(settings.OutputDir);

functions = {@example_planar_point_mass_trajectory, ...
    @example_terminal_defect_trajectory, ...
    @example_geometric_safety_pddp_2d_obstacle_avoidance, ...
    @example_geometric_safety_pddp_3d_obstacle_avoidance, ...
    @example_penalty_free_time_reactor_regulation, ...
    @example_free_time_pddp_vibration_regulation, ...
    @example_waypoint_pddp_pendulum, ...
    @example_thermal_regulation, ...
    @example_energy_storage_management};
results = cell(1, numel(functions));
for index = 1:numel(functions)
    name = func2str(functions{index});
    outputDir = fullfile(settings.OutputDir, name);
    results{index} = functions{index}('OutputDir', outputDir, ...
        'Visible', settings.Visible, 'QuickMode', settings.QuickMode);
end

allSucceeded = all(cellfun(@(entry) entry.solution.success, results));
if ~allSucceeded
    error('ddpack:examples:FailedChild', ...
        'One or more publication examples failed independent checks.');
end
summary = struct('success', allSucceeded, 'output_dir', settings.OutputDir, ...
    'results', {results});
summaryRows = cell(numel(results), 27);
for index = 1:numel(results)
    solution = results{index}.solution;
    summaryRows(index, :) = {results{index}.name, solution.algorithm_id, ...
        solution.algorithm_name, solution.implementation_status, ...
        solution.legacy_algorithm_name, solution.reference_relation, ...
        solution.success, solution.status, solution.objective, ...
        solution.terminal_error, solution.absolute_dynamics_defect, ...
        solution.metadata.metrics.high_accuracy_absolute_dynamics_defect, ...
        solution.metadata.defect_diagnostics.solver_consistent_max_step, ...
        solution.metadata.defect_diagnostics.solver_consistent_max_component, ...
        solution.maximum_state_constraint_violation, ...
        solution.maximum_control_constraint_violation, ...
        solution.min_obstacle_clearance, ...
        solution.metadata.metrics.initial_objective, ...
        solution.metadata.metrics.best_accepted_objective, ...
        solution.metadata.metrics.returned_objective, ...
        solution.metadata.metrics.accepted_iteration_count, ...
        solution.metadata.metrics.rejected_iteration_count, ...
        solution.iterations, solution.runtime_seconds, ...
        solution.termination_reason, ...
        solution.metadata.metrics.clearance_check_method, ...
        solution.metadata.metrics.finite_values_pass};
end
summaryTable = cell2table(summaryRows, 'VariableNames', ...
    {'example', 'algorithm_id', 'algorithm_name', 'implementation_status', ...
    'legacy_algorithm_name', 'reference_relation', ...
    'success', 'status', 'objective', ...
    'terminal_error', 'euler_defect', 'rk4_defect', ...
    'maximum_defect_segment', 'maximum_defect_state_component', ...
    'maximum_state_constraint_violation', ...
    'maximum_control_constraint_violation', 'minimum_obstacle_clearance', ...
    'initial_objective', 'best_accepted_objective', 'returned_objective', ...
    'accepted_iteration_count', 'rejected_iteration_count', ...
    'iteration_count', 'runtime_seconds', 'termination_reason', ...
    'clearance_check_method', 'finite_values_pass'});
writetable(summaryTable, fullfile(settings.OutputDir, 'example_summary.csv'));
summaryForFile = struct('success', allSucceeded, ...
    'output_dir', settings.OutputDir, 'table', table2struct(summaryTable));
save(fullfile(settings.OutputDir, 'example_summary.mat'), ...
    'summaryTable', 'summaryForFile');
writeText(fullfile(settings.OutputDir, 'example_summary.json'), ...
    jsonencode(summaryForFile, 'PrettyPrint', true));
writeText(fullfile(settings.OutputDir, 'example_summary.txt'), ...
    markdownSummary(summaryTable));
end

function value = markdownSummary(summaryTable)
lines = {'# DDPACK publication example summary', '', ...
    '| Example | Public algorithm | ID | Success | Terminal error | Euler defect | RK4 defect | Clearance | Runtime (s) |', ...
    '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |'};
for index = 1:height(summaryTable)
    lines{end+1} = sprintf('| %s | %s | `%s` | %d | %.6g | %.6g | %.6g | %.6g | %.6g |', ...
        summaryTable.example{index}, summaryTable.algorithm_name{index}, ...
        summaryTable.algorithm_id{index}, ...
        summaryTable.success(index), summaryTable.terminal_error(index), ...
        summaryTable.euler_defect(index), summaryTable.rk4_defect(index), ...
        summaryTable.minimum_obstacle_clearance(index), ...
        summaryTable.runtime_seconds(index)); %#ok<AGROW>
end
value = strjoin(lines, newline);
end

function writeText(filename, value)
fileId = fopen(filename, 'w');
if fileId < 0, error('ddpack:examples:WriteFailed', 'Cannot write %s.', filename); end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
fprintf(fileId, '%s', value);
end
