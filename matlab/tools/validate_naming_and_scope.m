function report = validate_naming_and_scope(varargin)
%VALIDATE_NAMING_AND_SCOPE Audit Route 2 public identities and scope claims.
parser = inputParser;
addParameter(parser, 'OutputDir', '', @(x) ischar(x) || isstring(x));
parse(parser, varargin{:});
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));

registry = ddpack.algorithmRegistry();
requiredFields = {'algorithm_id', 'public_name', 'short_name', ...
    'legacy_names', 'implementation_status', 'theoretical_scope', ...
    'reference_relation', 'stable_or_experimental', 'public_entry_point', ...
    'legacy_entry_points', 'limitations', 'recommended_citation_text'};
expectedStable = {'free_time_pddp', 'waypoint_pddp', ...
    'terminal_defect_pddp', 'geometric_safety_pddp_2d', ...
    'geometric_safety_pddp_3d', 'penalty_free_time_ddp'};
legacyStable = {'pddp', 'c_pddp', 'mspddp', 'cbf_mspddp_2d', ...
    'cbf_mspddp_3d', 'fft_cddp'};

checks = cell(0, 3);
record('registry_fields', all(isfield(registry, requiredFields)), ...
    'Every registry record has the required identity fields.');
ids = {registry.algorithm_id};
record('registry_unique_ids', numel(unique(ids)) == numel(ids), ...
    'Algorithm identifiers are unique.');
stable = registry(strcmp({registry.stable_or_experimental}, 'stable'));
experimental = registry(strcmp({registry.stable_or_experimental}, 'experimental'));
record('stable_registry_set', isequal(sort({stable.algorithm_id}), sort(expectedStable)), ...
    'The stable set is exactly the six validated implementation variants.');
record('experimental_registry_empty', isempty(experimental), ...
    'The public registry contains only the six maintained solvers.');

for index = 1:numel(stable)
    entry = stable(index);
    publicFile = fullfile(repoRoot, 'matlab', 'src', 'algorithms', ...
        [entry.public_entry_point '.m']);
    record(['public_entry_' entry.algorithm_id], isfile(publicFile), ...
        ['Canonical entry exists: ' entry.public_entry_point '.m']);
    for legacyIndex = 1:numel(entry.legacy_entry_points)
        legacy = entry.legacy_entry_points{legacyIndex};
        wrapperFile = fullfile(repoRoot, 'matlab', 'src', 'algorithms', [legacy '.m']);
        wrapperPass = false;
        if isfile(wrapperFile)
            wrapperText = fileread(wrapperFile);
            wrapperPass = contains(wrapperText, 'ddpack:DeprecatedAlgorithmName') && ...
                contains(wrapperText, [entry.public_entry_point '(']) && ...
                isempty(regexp(wrapperText, '^\s*(for|while)\s+', 'once', 'lineanchors'));
        end
        record(['legacy_wrapper_' legacy], wrapperPass, ...
            ['Deprecated wrapper forwards ' legacy ' to ' entry.public_entry_point '.']);
    end
end

runnerText = fileread(fullfile(repoRoot, 'matlab', 'examples', 'run_publication_examples.m'));
record('formal_runner_uses_canonical_names', ...
    ~any(cellfun(@(name) contains(runnerText, ['example_' name]), legacyStable)), ...
    'The publication runner does not call historical example identities.');
record('formal_dynamic_examples', ...
    contains(runnerText, 'example_thermal_regulation') && ...
    contains(runnerText, 'example_energy_storage_management') && ...
    isfile(fullfile(repoRoot, 'matlab', 'examples', 'dynamic_optimization', ...
        'thermal_regulation', 'example_thermal_regulation.m')) && ...
    isfile(fullfile(repoRoot, 'matlab', 'examples', 'dynamic_optimization', ...
        'energy_storage_management', 'example_energy_storage_management.m')), ...
    'Thermal regulation and energy storage are formal examples.');

manualText = fileread(fullfile(repoRoot, 'DDPACK_Manual', 'DDPACK_Manual.tex'));
record('manual_canonical_ids', all(cellfun(@(id) contains(manualText, id), ...
    expectedStable)), 'The LaTeX manual lists every canonical stable identifier.');
record('manual_scope', contains(manualText, '有限时域') && ...
    contains(manualText, '静态非线性规划') && contains(manualText, 'G_j'), ...
    'The LaTeX manual states the finite-horizon scope, static-NLP limitation, and constraint sign.');

manuscriptText = fileread(fullfile(repoRoot, 'README.rst'));
forbiddenClaims = {'is a general-purpose optimization', ...
    'solves arbitrary nonlinear optimization', 'solves any optimization problem', ...
    'is a universal optimization solver', 'faithfully reproduces', ...
    'exactly implements', 'complete implementation of'};
record('public_documentation_scope_language', ...
    ~any(cellfun(@(claim) contains(lower(manuscriptText), claim), forbiddenClaims)) && ...
    contains(manuscriptText, 'Implementation scope and differences') && ...
    contains(lower(manuscriptText), 'package-specific implementation variants'), ...
    'The public documentation uses qualified package-specific scope language.');

differenceText = manualText;
record('implementation_differences', ...
    all(cellfun(@(name) contains(differenceText, name), legacyStable(3:end))) && ...
    contains(differenceText, '完整多重射击') && contains(differenceText, 'FFT'), ...
    'The manual discloses the material historical-name limitations.');

constraintText = fileread(fullfile(repoRoot, 'matlab', 'src', 'constraints', 'Constraints.m'));
helperText = fileread(fullfile(repoRoot, 'matlab', 'src', '+ddpack', ...
    'feasibilityFromLessEqual.m'));
record('constraint_convention', contains(constraintText, 'G(x,u) >= 0') && ...
    contains(helperText, 'G = -c', 'IgnoreCase', true) && ...
    contains(manualText, 'G_j'), ...
    'Public constraints consistently use G(x,u) >= 0 feasible.');

solutionText = fileread(fullfile(repoRoot, 'matlab', 'src', '+ddpack', 'normalizeSolution.m'));
resultFields = {'algorithm_id', 'algorithm_name', 'implementation_status', ...
    'legacy_algorithm_name', 'reference_relation'};
record('result_identity_fields', all(cellfun(@(name) contains(solutionText, ...
    ['''' name '''']), resultFields)), ...
    'Normalized results expose the complete algorithm identity.');

checkTable = cell2table(checks, ...
    'VariableNames', {'check', 'passed', 'detail'});
success = all(checkTable.passed);
if success, status = 'PASS'; else, status = 'FAIL'; end
report = struct('success', success, 'status', status, ...
    'generality_level', 'G2_LIMITED', 'stable_algorithm_count', numel(stable), ...
    'experimental_algorithm_count', numel(experimental), ...
    'checks', table2struct(checkTable));

outputDir = char(parser.Results.OutputDir);
if ~isempty(outputDir)
    if ~isfolder(outputDir), mkdir(outputDir); end
    writetable(checkTable, fullfile(outputDir, 'naming_and_scope_checks.csv'));
    writeText(fullfile(outputDir, 'naming_and_scope_report.json'), ...
        jsonencode(report, 'PrettyPrint', true));
    writeText(fullfile(outputDir, 'naming_and_scope_report.txt'), ...
        markdownReport(checkTable, report));
end
if ~success
    failed = strjoin(checkTable.check(~checkTable.passed), ', ');
    error('ddpack:scope:ValidationFailed', ...
        'Naming and scope checks failed: %s', failed);
end

    function record(name, passed, detail)
        checks(end + 1, :) = {name, logical(passed), detail}; %#ok<AGROW>
    end
end

function value = markdownReport(data, report)
lines = {'# Naming and scope audit', '', ...
    ['NAMING_AND_SCOPE_STATUS: **' report.status '**'], ...
    ['GENERALITY_LEVEL: **' report.generality_level '**'], '', ...
    '| Check | Passed | Detail |', '| --- | ---: | --- |'};
for index = 1:height(data)
    lines{end + 1} = sprintf('| `%s` | %d | %s |', ...
        data.check{index}, data.passed(index), data.detail{index}); %#ok<AGROW>
end
value = strjoin(lines, newline);
end

function writeText(filename, value)
fileId = fopen(filename, 'w');
if fileId < 0
    error('ddpack:scope:WriteFailed', 'Cannot write %s.', filename);
end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
fprintf(fileId, '%s', value);
end
