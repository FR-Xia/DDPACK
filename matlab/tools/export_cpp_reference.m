function export_cpp_reference(outputDir)
%EXPORT_CPP_REFERENCE Export native-port reference data from unchanged solvers.
% No plots or toolboxes are needed. Case definitions come from the formal
% MATLAB examples, so changes in those examples invalidate native parity.
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(fullfile(repoRoot, 'matlab', 'tools')); setup_ddpack;
if nargin < 1, outputDir = fullfile(repoRoot, 'cpp', 'tests', 'reference'); end
if isfolder(outputDir)
    error('ddpack:reference:Exists', 'Use a fresh reference directory.');
end
mkdir(outputDir);
names = {'vibration','planar','terminal_defect','obstacle_2d','obstacle_3d', ...
    'reactor','pendulum','thermal','storage'};
files = {'examples/basic/example_free_time_pddp_vibration_regulation.m', ...
    'examples/trajectory/example_planar_point_mass_trajectory.m', ...
    'examples/trajectory/example_terminal_defect_trajectory.m', ...
    'examples/trajectory/example_geometric_safety_pddp_2d_obstacle_avoidance.m', ...
    'examples/trajectory/example_geometric_safety_pddp_3d_obstacle_avoidance.m', ...
    'examples/cross_domain/example_penalty_free_time_reactor_regulation.m', ...
    'examples/cross_domain/example_waypoint_pddp_pendulum.m', ...
    'examples/dynamic_optimization/thermal_regulation/example_thermal_regulation.m', ...
    'examples/dynamic_optimization/energy_storage_management/example_energy_storage_management.m'};
for index = 1:numel(names)
    [problem, options] = caseDefinition(fullfile(repoRoot, 'matlab', files{index}));
    target = fullfile(outputDir, names{index}); mkdir(target);
    if strcmp(names{index}, 'vibration')
        state = rng;
        n = floor(problem.tf / problem.dt);
        initial = zeros(numel(problem.u_max), n);
        for k = 1:n-1
            initial(:,k) = 2 .* problem.u_max .* rand(numel(problem.u_max), 1) - problem.u_max;
        end
        writematrix(initial, fullfile(target, 'initial_controls.csv'));
        rng(state);
    end
    % The local periodic-error callback belongs to the original example.
    % It does not affect optimization, and parity compares states directly.
    if isfield(problem, 'terminal_error_function')
        problem = rmfield(problem, 'terminal_error_function');
    end
    logText = evalc('solution = ddpack.solve(problem, options);');
    writematrix(solution.states, fullfile(target, 'states.csv'));
    writematrix(solution.controls, fullfile(target, 'controls.csv'));
    writematrix(solution.time, fullfile(target, 'time.csv'));
    writematrix(solution.trial_cost_history, fullfile(target, 'trial.csv'));
    writematrix(solution.metadata.metrics.returned_objective,fullfile(target,'returned_objective.csv'));
    if isfield(solution.raw,'line_search')
        writematrix(solution.raw.line_search.trials,fullfile(target,'line_search_trials.csv'));
        writematrix(solution.raw.M(:),fullfile(target,'merit.csv'));
    end
    if isfield(solution.raw,'geometric_refinement')
        writematrix(solution.raw.geometric_refinement.starts,fullfile(target,'refinement_starts.csv'));
        writematrix(solution.raw.geometric_refinement.penalty_history(:),fullfile(target,'refinement_penalty_history.csv'));
    end
    writematrix([solution.terminal_error, solution.absolute_dynamics_defect, ...
        solution.metadata.metrics.high_accuracy_absolute_dynamics_defect, ...
        solution.min_obstacle_clearance], fullfile(target, 'metrics.csv'));
    fid = fopen(fullfile(target, 'solver.txt'), 'w');
    fprintf(fid, '%s', logText); fclose(fid);
    oneStepProblem = problem;
    oneStepProblem.terminal_projection_max_iterations = 0;
    oneStepProblem.geometric_refinement_iterations = 0;
    oneStepOptions = ddpack.Options('Algorithm', options.Algorithm, ...
        'MaxIterations', 1, 'Alpha', options.Alpha, 'Epsilon', options.Epsilon, ...
        'Rho', options.Rho, 'UpdateEpsilon', options.UpdateEpsilon);
    if strcmp(names{index}, 'vibration'), rng(state); end
    evalc('first = ddpack.solve(oneStepProblem, oneStepOptions);');
    writematrix(first.states, fullfile(target, 'first_states.csv'));
    writematrix(first.controls, fullfile(target, 'first_controls.csv'));
    fprintf('%s reference exported\n', names{index});
end
fid = fopen(fullfile(outputDir, 'PROVENANCE.txt'), 'w');
fprintf(fid, 'Generated by matlab/tools/export_cpp_reference.m\nMATLAB %s\n', version);
fprintf(fid, 'Date: %s\n', char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')));
fprintf(fid, 'Scope: nine full-iteration formal example configurations.\n');
fclose(fid);
sourceFiles = dir(fullfile(repoRoot, 'matlab', 'src', '**', '*.m'));
hashes = strings(numel(sourceFiles), 2);
for k = 1:numel(sourceFiles)
    filename = fullfile(sourceFiles(k).folder, sourceFiles(k).name);
    hashes(k,1) = replace(erase(filename, [repoRoot filesep]), filesep, '/');
    digest = java.security.MessageDigest.getInstance('SHA-256');
    fid = fopen(filename, 'rb'); bytes = fread(fid, Inf, '*uint8'); fclose(fid);
    digest.update(bytes);
    hashes(k,2) = lower(reshape(dec2hex(typecast(digest.digest(), 'uint8'), 2).', 1, []));
end
writetable(array2table(hashes, 'VariableNames', {'file','sha256'}), ...
    fullfile(outputDir, 'MATLAB_SOURCE_SHA256.csv'));
end

function [problem, options] = caseDefinition(source)
text = fileread(source);
lines = splitlines(string(text));
lines(1) = "";
lines(startsWith(strtrim(lines), "settings = ddpack.exampleSettings")) = "";
text = char(join(lines, newline));
stop = strfind(text, 'solverLog =');
text = text(1:stop(1)-1);
settings = struct('QuickMode', false); %#ok<NASGU>
eval(text);
end
