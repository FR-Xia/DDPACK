function [problem, options] = comparison_case(name)
%COMPARISON_CASE Reuse the full formal example setup without plotting or I/O.
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
names = {'vibration','planar','terminal_defect','obstacle_2d','obstacle_3d', ...
    'reactor','pendulum','thermal','storage'};
files = {'basic/example_free_time_pddp_vibration_regulation.m', ...
    'trajectory/example_planar_point_mass_trajectory.m', ...
    'trajectory/example_terminal_defect_trajectory.m', ...
    'trajectory/example_geometric_safety_pddp_2d_obstacle_avoidance.m', ...
    'trajectory/example_geometric_safety_pddp_3d_obstacle_avoidance.m', ...
    'cross_domain/example_penalty_free_time_reactor_regulation.m', ...
    'cross_domain/example_waypoint_pddp_pendulum.m', ...
    'dynamic_optimization/thermal_regulation/example_thermal_regulation.m', ...
    'dynamic_optimization/energy_storage_management/example_energy_storage_management.m'};
index = find(strcmp(names, name), 1);
assert(~isempty(index), 'Unknown comparison case.');
lines = splitlines(string(fileread(fullfile(root,'matlab','examples',files{index}))));
lines(1) = "";
lines(startsWith(strtrim(lines), "settings = ddpack.exampleSettings")) = "";
text = char(join(lines, newline)); stop = strfind(text, 'solverLog =');
text = text(1:stop(1)-1);
settings = struct('QuickMode', false); %#ok<NASGU>
eval(text);
if strcmp(name, 'pendulum')
    problem.terminal_error_function = @(state,target) norm([ ...
        mod(state(1)-target(1)+pi,2*pi)-pi; state(2)-target(2)]);
end
end
