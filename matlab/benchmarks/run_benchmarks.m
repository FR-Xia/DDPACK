function problem = pendulumProblem()
problem = struct('name', 'inverted_pendulum_swingup', ...
    'x0', [pi; 0], 'xf', [0; 0], 'tf', 5, 'dt', 0.05, ...
    'dynamics', InvertedPendulumDynamics(1, 1, 9.81, 0.1), ...
    'cost', InvertedPendulumCost(diag([100, 10]), diag([1, 0.1]), ...
        0.1, [0; 0]), 'u_max', 10, 'freetime', false, 'montecarlo', 0, ...
    'terminal_tolerance', 1e-2, 'constraint_tolerance', 1e-8, ...
    'terminal_error_function', @periodicTerminalError);
end

function value = periodicTerminalError(state, target)
angleError = mod(state(1) - target(1) + pi, 2*pi) - pi;
value = norm([angleError; state(2) - target(2)]);
end

function tableOut = benchmarkOverhead(repeatCount)
rng(4, 'twister');
problem = ddpack.problems.linearRegulation();
evalc('solution = ddpack.solve(problem, ddpack.Options(''Algorithm'', ''free_time_pddp''));');
runOverheadOperation('normalize', solution, problem);
runOverheadOperation('save', solution, problem);
runOverheadOperation('headless_plot', solution, problem);
rows = cell(repeatCount * 3, 3); row = 0;
operations = {'normalize', 'save', 'headless_plot'};
for operationIndex = 1:numel(operations)
    for repeat = 1:repeatCount
        row = row + 1;
        started = tic;
        runOverheadOperation(operations{operationIndex}, solution, problem);
        rows(row, :) = {operations{operationIndex}, repeat, toc(started)};
    end
end
raw = cell2table(rows, 'VariableNames', {'operation', 'repeat', 'runtime_seconds'});
summary = cell(3, 8);
for operationIndex = 1:numel(operations)
    values = raw.runtime_seconds(strcmp(raw.operation, operations{operationIndex}));
    summary(operationIndex, :) = {operations{operationIndex}, repeatCount, ...
        median(values), mean(values), std(values), min(values), max(values), ...
        percentile95(values)};
end
tableOut = cell2table(summary, 'VariableNames', {'operation', 'repeat_count', ...
    'runtime_median', 'runtime_mean', 'runtime_std', 'runtime_min', ...
    'runtime_max', 'runtime_p95'});
end

function runOverheadOperation(operation, solution, problem)
switch operation
    case 'normalize'
        ddpack.normalizeSolution(solution.raw, solution.algorithm, problem, 0);
    case 'save'
        filename = [tempname, '.mat'];
        cleanup = onCleanup(@() deleteIfPresent(filename)); %#ok<NASGU>
        ddpack.save(solution, filename);
    case 'headless_plot'
        figureHandle = ddpack.plot(solution, 'Visible', false);
        close(figureHandle);
end
end

function deleteIfPresent(filename)
if isfile(filename), delete(filename); end
end

function writeText(filename, value)
fileId = fopen(filename, 'w');
if fileId < 0, error('ddpack:benchmark:WriteFailed', 'Cannot write %s.', filename); end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
fprintf(fileId, '%s', value);
end

function value = percentile95(values)
values = sort(values(isfinite(values)));
if isempty(values), value = NaN; return; end
position = 1 + 0.95 * (numel(values) - 1);
lowerIndex = floor(position); upperIndex = ceil(position);
if lowerIndex == upperIndex
    value = values(lowerIndex);
else
    fraction = position - lowerIndex;
    value = values(lowerIndex) + fraction * ...
        (values(upperIndex) - values(lowerIndex));
end
end

function value = finiteMinimum(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = min(values); end
end

function metadata = environmentMetadata()
if ispc
    [~, osText] = system('ver');
    cpu = getenv('PROCESSOR_IDENTIFIER');
else
    [~, osText] = system('uname -a');
    cpu = getenv('HOSTTYPE');
end
ramBytes = NaN;
try
    memoryInfo = memory;
    ramBytes = memoryInfo.MemAvailableAllArrays;
catch
end
metadata = struct('matlab_version', version, 'computer', computer, ...
    'architecture', computer('arch'), 'operating_system', strtrim(osText), ...
    'cpu', cpu, 'available_memory_bytes', ramBytes);
end

function value = benchmarkMarkdown(summaryTable, overheadTable, metadata)
lines = {'# DDPACK benchmark summary', '', ...
    sprintf('- MATLAB: %s', metadata.environment.matlab_version), ...
    sprintf('- Platform: %s', metadata.environment.operating_system), ...
    sprintf('- Warmups per case: %d', metadata.warmup_runs_per_case), ...
    sprintf('- Measured repeats per case: %d', metadata.repeat_count), ...
    '- Parallel execution: false', '', ...
    '| Case | Algorithm | Median solver (s) | Mean (s) | Std (s) | P95 (s) |', ...
    '| --- | --- | ---: | ---: | ---: | ---: |'};
for index = 1:height(summaryTable)
    lines{end+1} = sprintf('| %s | `%s` | %.6g | %.6g | %.6g | %.6g |', ...
        summaryTable.case_name{index}, summaryTable.algorithm{index}, ...
        summaryTable.solver_runtime_median(index), ...
        summaryTable.solver_runtime_mean(index), ...
        summaryTable.solver_runtime_std(index), ...
        summaryTable.solver_runtime_p95(index)); %#ok<AGROW>
end
lines = [lines, {'', '## API overhead', '', ...
    '| Operation | Median (s) | Mean (s) | Std (s) | P95 (s) |', ...
    '| --- | ---: | ---: | ---: | ---: |'}]; %#ok<AGROW>
for index = 1:height(overheadTable)
    lines{end+1} = sprintf('| %s | %.6g | %.6g | %.6g | %.6g |', ...
        overheadTable.operation{index}, overheadTable.runtime_median(index), ...
        overheadTable.runtime_mean(index), overheadTable.runtime_std(index), ...
        overheadTable.runtime_p95(index)); %#ok<AGROW>
end
lines = [lines, {'', ['Absolute times describe only this recorded environment; ' ...
    'no cross-machine performance claim is made.']}]; %#ok<AGROW>
value = strjoin(lines, newline);
end

function value = htmlEscape(value)
value = strrep(value, '&', '&amp;');
value = strrep(value, '<', '&lt;');
value = strrep(value, '>', '&gt;');
end
