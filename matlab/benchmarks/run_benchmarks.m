        diag([0.05, 0.05, 0.05, 0.01, 0.05, 0.05]), 0.2*eye(2)), ...
    'u_max', [1.5; 1.5], 'obstacle_centers', target * (24/49), ...
    'obstacle_radii', 0.18, 'safety_margin', 0.04, ...
    'geometric_enforcement_margin', 0.15, 'safety_gain', 0.2, ...
    'minimum_time', 5.20, 'maximum_time', 5.25, ...
    'terminal_projection_tolerance', 0.005, ...
    'terminal_projection_max_iterations', 30, ...
    'terminal_tolerance', 0.005, 'constraint_tolerance', 1e-8, ...
    'independent_dynamics_defect_tolerance', 0.02);
