function report = run_benchmarks(varargin)
%RUN_BENCHMARKS Reproducible stable-scope and API-overhead benchmarks.
parser = inputParser;
addParameter(parser, 'OutputDir', '', @(x) ischar(x) || isstring(x));
addParameter(parser, 'WarmupCount', 3, ...
    @(x) isnumeric(x) && isscalar(x) && x >= 3 && x == floor(x));
addParameter(parser, 'RepeatCount', 5, ...
    @(x) isnumeric(x) && isscalar(x) && x >= 3 && x == floor(x));
parse(parser, varargin{:}); settings = parser.Results;

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(fullfile(repoRoot, 'matlab', 'tools'));
setup_ddpack;
if strlength(string(settings.OutputDir)) == 0
    stamp = char(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));
    settings.OutputDir = fullfile(repoRoot, 'artifacts', 'benchmarks', ['run_' stamp]);
end
outputDir = char(settings.OutputDir);
if isfolder(outputDir)
    error('ddpack:benchmark:ExistingOutput', ...
        'Refusing to overwrite benchmark output: %s', outputDir);
end
mkdir(outputDir);

cases = benchmarkCases();
rawRows = cell(numel(cases) * settings.RepeatCount, 13);
warmupRows = cell(numel(cases) * settings.WarmupCount, 4);
row = 0;
warmupRow = 0;
for caseIndex = 1:numel(cases)
    solver = cases(caseIndex).solve;
    postprocess = cases(caseIndex).postprocess;
    for warmupIndex = 1:settings.WarmupCount
        rng(cases(caseIndex).seed, 'twister');
        started = tic;
        evalc('warmup = solver();');
        elapsed = toc(started);
        warmup = postprocess(warmup);
        assert(warmup.success, '%s warmup failed: %s', ...
            cases(caseIndex).name, warmup.message);
        warmupRow = warmupRow + 1;
        warmupRows(warmupRow, :) = {cases(caseIndex).name, ...
            cases(caseIndex).algorithm, warmupIndex, elapsed};
    end
    for repeat = 1:settings.RepeatCount
        rng(cases(caseIndex).seed, 'twister');
        wallClock = tic;
        evalc('solution = solver();');
        wallSeconds = toc(wallClock);
        solution = postprocess(solution);
        assert(solution.success, '%s benchmark failed: %s', ...
            cases(caseIndex).name, solution.message);
        row = row + 1;
        rawRows(row, :) = {cases(caseIndex).name, solution.algorithm, repeat, ...
            solution.success, solution.runtime_seconds, wallSeconds, ...
            solution.terminal_error, solution.absolute_dynamics_defect, ...
            solution.metadata.metrics.high_accuracy_absolute_dynamics_defect, ...
            solution.max_constraint_violation, solution.min_obstacle_clearance, ...
            solution.objective, solution.iterations};
    end
end
warmupTable = cell2table(warmupRows, 'VariableNames', ...
    {'case_name', 'algorithm', 'warmup', 'wall_runtime_seconds'});
writetable(warmupTable, fullfile(outputDir, 'benchmark_warmups.csv'));
rawTable = cell2table(rawRows, 'VariableNames', {'case_name', 'algorithm', ...
    'repeat', 'success', 'solver_runtime_seconds', 'wall_runtime_seconds', ...
    'terminal_error', 'euler_defect', 'rk4_defect', ...
    'maximum_constraint_violation', 'minimum_obstacle_clearance', ...
    'objective', 'iteration_count'});
writetable(rawTable, fullfile(outputDir, 'benchmark_repeats.csv'));

summaryRows = cell(numel(cases), 24);
for caseIndex = 1:numel(cases)
    selected = strcmp(rawTable.case_name, cases(caseIndex).name);
    solverTime = rawTable.solver_runtime_seconds(selected);
    wallTime = rawTable.wall_runtime_seconds(selected);
    terminal = rawTable.terminal_error(selected);
    eulerDefect = rawTable.euler_defect(selected);
    rk4Defect = rawTable.rk4_defect(selected);
    summaryRows(caseIndex, :) = {cases(caseIndex).name, cases(caseIndex).algorithm, ...
        cases(caseIndex).seed, settings.WarmupCount, settings.RepeatCount, ...
        median(solverTime), mean(solverTime), std(solverTime), ...
        min(solverTime), max(solverTime), percentile95(solverTime), ...
        median(wallTime), mean(wallTime), std(wallTime), ...
        min(wallTime), max(wallTime), percentile95(wallTime), median(terminal), ...
        max(eulerDefect), max(rk4Defect), ...
        max(rawTable.maximum_constraint_violation(selected)), ...
        finiteMinimum(rawTable.minimum_obstacle_clearance(selected)), ...
        median(rawTable.objective(selected)), ...
        median(rawTable.iteration_count(selected))};
end
summaryTable = cell2table(summaryRows, 'VariableNames', {'case_name', 'algorithm', ...
    'random_seed', 'warmup_count', 'repeat_count', ...
    'solver_runtime_median', 'solver_runtime_mean', 'solver_runtime_std', ...
    'solver_runtime_min', 'solver_runtime_max', 'solver_runtime_p95', ...
    'wall_runtime_median', 'wall_runtime_mean', 'wall_runtime_std', ...
    'wall_runtime_min', 'wall_runtime_max', 'wall_runtime_p95', ...
    'terminal_error_median', 'euler_defect_max', ...
    'rk4_defect_max', 'maximum_constraint_violation', ...
    'minimum_obstacle_clearance', 'objective_median', 'iteration_count_median'});
writetable(summaryTable, fullfile(outputDir, 'benchmark_summary.csv'));

overheadTable = benchmarkOverhead(settings.RepeatCount);
writetable(overheadTable, fullfile(outputDir, 'api_overhead.csv'));
environment = environmentMetadata();
metadata = struct('warmup_runs_per_case', settings.WarmupCount, ...
    'repeat_count', settings.RepeatCount, ...
    'tier_a_common_problem_comparison', 'not_reported', ...
        'tier_a_reason', ['No common problem was found on which the free-time and terminal-defect variants ' ...
        'passed the same validation tolerances; incompatible algorithms are not ranked.'], ...
    'tier_b_scope', 'algorithm-specific verified cases', ...
    'tier_c_scope', 'normalize/save/headless-plot overhead', ...
    'environment', environment, ...
    'parallel_execution', false, ...
    'generated_at', char(datetime('now', 'TimeZone', 'local')));
writeText(fullfile(outputDir, 'benchmark_metadata.json'), ...
    jsonencode(metadata, 'PrettyPrint', true));
writeText(fullfile(outputDir, 'benchmark_summary.json'), ...
    jsonencode(table2struct(summaryTable), 'PrettyPrint', true));
save(fullfile(outputDir, 'benchmark_results.mat'), 'warmupTable', ...
    'rawTable', 'summaryTable', 'overheadTable', 'metadata');
markdown = benchmarkMarkdown(summaryTable, overheadTable, metadata);
writeText(fullfile(outputDir, 'benchmark_summary.txt'), markdown);
writeText(fullfile(outputDir, 'benchmark_summary.html'), ...
    ['<html><body><pre>' htmlEscape(markdown) '</pre></body></html>']);
report = struct('success', true, 'output_dir', outputDir, ...
    'summary', summaryTable, 'warmups', warmupTable, ...
    'repeats', rawTable, 'overhead', overheadTable, 'metadata', metadata);
end

function cases = benchmarkCases()
identity = @(solution) solution;
cases = struct( ...
    'name', {'free_time_pddp_linear_regulation', 'waypoint_pddp_pendulum', ...
        'terminal_defect_pddp_trajectory', 'geometric_safety_pddp_2d', ...
        'geometric_safety_pddp_3d', 'penalty_free_time_ddp_reactor'}, ...
    'algorithm', {'free_time_pddp', 'waypoint_pddp', 'terminal_defect_pddp', ...
        'geometric_safety_pddp_2d', 'geometric_safety_pddp_3d', ...
        'penalty_free_time_ddp'}, ...
    'seed', {4, 13, 22, 23, 24, 17}, ...
    'solve', {@solveFreeTime, @solveWaypoint, @solveTerminalDefect, ...
        @solveGeometric2d, @solveGeometric3d, @solvePenaltyFreeTime}, ...
    'postprocess', {identity, identity, identity, identity, ...
        identity, identity});
end

function solution = solveFreeTime()
problem = ddpack.problems.linearRegulation();
solution = ddpack.solve(problem, ddpack.Options( ...
    'Algorithm', 'free_time_pddp', 'MaxIterations', 80, 'Alpha', 0.2));
end

